// Command Group: "Sequence Evolution & Reconstruction"

// Reconstruct ancient sequences using extant genomes and a newick tree with branch lengths
package main

import (
	"flag"
	"fmt"
	"log"
	"os"

	"github.com/vertgenlab/gonomics/bed"
	"github.com/vertgenlab/gonomics/exception"
	"github.com/vertgenlab/gonomics/reconstruct/ilsReconstruct"
	"github.com/vertgenlab/gonomics/wig"
)

// IlsWigToBedSettings defines the usage settings for the ilsWigToBed command
type IlsWigToBedSettings struct {
	PostProbWig string
	ChromName   string
	ChromSizes  string
	OutPath     string
}

// IlsWigToBedUsage defines the usage statement for the ilsWigToBed command
func IlsWigToBedUsage(IlsWigToBedFlags *flag.FlagSet) {
	fmt.Print(
		"ilsWigToBed converts probability wig tracks, as generated by postProbToWig, to BED regions specifying the maximum posterior probability.\n" +
			"Usage:\n" +
			"ilsWigToBed <posterior-probabilities>.wig chromName chrSizes.chrom.sizes outPath\n" +
			"options:\n")
	IlsWigToBedFlags.PrintDefaults()
}

// parseIlsWigToBedArgs is the main function of the IlsWigToBed command. It parses options and runs the ilsWigToBed function.
func parseIlsWigToBedArgs() {
	expectedNumArgs := 4
	var err error
	IlsWigToBedFlags := flag.NewFlagSet("IlsWigToBed", flag.ExitOnError)

	IlsWigToBedFlags.Usage = func() { IlsWigToBedUsage(IlsWigToBedFlags) }
	err = IlsWigToBedFlags.Parse(os.Args[3:])

	exception.PanicOnErr(err)

	if len(IlsWigToBedFlags.Args()) != expectedNumArgs {
		IlsWigToBedFlags.Usage()
		log.Fatalf("Error: expecting %d arguments, but got %d\n",
			expectedNumArgs, len(IlsWigToBedFlags.Args()))
	}

	postProbWig := IlsWigToBedFlags.Arg(0)
	chromName := IlsWigToBedFlags.Arg(1)
	chromSizes := IlsWigToBedFlags.Arg(2)
	outDir := IlsWigToBedFlags.Arg(3)

	s := IlsWigToBedSettings{
		PostProbWig: postProbWig,
		ChromName:   chromName,
		ChromSizes:  chromSizes,
		OutPath:     outDir,
	}

	IlsWigToBed(s)
}

func IlsWigToBed(s IlsWigToBedSettings) {
	postProbWig := wig.Read(s.PostProbWig, s.ChromSizes, 0)

	out := ilsReconstruct.IlsWigToBed(postProbWig, s.ChromName)

	bed.Write(s.OutPath, out)
}

func main() {
	parseIlsWigToBedArgs()
}
